# TAB 2 — CANDIDATE SCREENING
# ============================================================

with tab2:

    st.subheader("Target-band-gap candidate screening")

    if predictions.empty:

        st.error(
            "The full screening file was not found. Expected: "
            "results/all_material_predictions.csv"
        )

    else:

        st.write(
            "Search the complete JARVIS-DFT dataset using the selected "
            "target band gap, prediction tolerance, and Random Forest "
            "uncertainty proxy. These are known materials retrospectively "
            "prioritized by the model; this is a screening demonstration, "
            "not a claim of experimental discovery."
        )

        # ----------------------------------------------------
        # SCREENING CONTROLS
        # ----------------------------------------------------

        c1, c2, c3 = st.columns(3)

        target = c1.number_input(
            "Target band gap (eV)",
            min_value=0.0,
            max_value=10.0,
            value=1.5,
            step=0.1,
        )

        max_distance = c2.slider(
            "Maximum predicted distance (eV)",
            min_value=0.01,
            max_value=2.0,
            value=0.10,
            step=0.01,
        )

        max_uncertainty = c3.slider(
            "Maximum uncertainty proxy (eV)",
            min_value=0.01,
            max_value=2.0,
            value=0.40,
            step=0.01,
        )

        # ----------------------------------------------------
        # FILTER MATERIALS
        # ----------------------------------------------------

        df = predictions.copy()

        if (
            "predicted_bandgap" not in df.columns
            or "prediction_uncertainty" not in df.columns
        ):

            st.error(
                "The screening file does not contain the required "
                "'predicted_bandgap' and/or 'prediction_uncertainty' columns."
            )

        else:

            df["distance_from_selected_target"] = (
                df["predicted_bandgap"] - target
            ).abs()

            filtered = df[
                (
                    df["distance_from_selected_target"]
                    <= max_distance
                )
                &
                (
                    df["prediction_uncertainty"]
                    <= max_uncertainty
                )
            ].sort_values(
                [
                    "distance_from_selected_target",
                    "prediction_uncertainty",
                ]
            )

            # ------------------------------------------------
            # RESULT COUNT
            # ------------------------------------------------

            st.success(
                f"Found **{len(filtered):,}** matching materials "
                f"out of **{len(df):,}** total materials."
            )

            # ------------------------------------------------
            # TOP MATCH INFORMATION
            # ------------------------------------------------

            if not filtered.empty:

                m1, m2, m3 = st.columns(3)

                m1.metric(
                    "Closest predicted band gap",
                    f"{filtered.iloc[0]['predicted_bandgap']:.3f} eV",
                )

                if "formula" in filtered.columns:

                    m2.metric(
                        "Closest material",
                        str(filtered.iloc[0]["formula"]),
                    )

                else:

                    m2.metric(
                        "Closest material",
                        "N/A",
                    )

                m3.metric(
                    "Lowest uncertainty",
                    f"{filtered['prediction_uncertainty'].min():.3f} eV",
                )

                # ------------------------------------------------
                # RESULTS TABLE
                # ------------------------------------------------

                display_cols = [
                    "jid",
                    "formula",
                    "predicted_bandgap",
                    "prediction_uncertainty",
                    "target_bandgap",
                    "crys",
                    "spg_number",
                ]

                available = [
                    c
                    for c in display_cols
                    if c in filtered.columns
                ]

                st.markdown("### Matching materials")

                st.dataframe(
                    filtered[available].head(100),
                    use_container_width=True,
                    hide_index=True,
                )

                # ------------------------------------------------
                # BAR CHART
                # ------------------------------------------------

                st.markdown(
                    "### Predicted band gaps of top matches"
                )

                if "formula" in filtered.columns:

                    chart_df = (
                        filtered[
                            [
                                "formula",
                                "predicted_bandgap",
                            ]
                        ]
                        .head(30)
                        .copy()
                    )

                    chart_df["formula"] = (
                        chart_df["formula"].astype(str)
                    )

                    chart_df = chart_df.set_index("formula")

                    st.bar_chart(
                        chart_df,
                        use_container_width=True,
                    )

                # ------------------------------------------------
                # DOWNLOAD
                # ------------------------------------------------

                st.download_button(
                    "Download filtered candidates as CSV",
                    data=filtered.to_csv(
                        index=False
                    ).encode("utf-8"),
                    file_name="filtered_bandgap_candidates.csv",
                    mime="text/csv",
                    use_container_width=True,
                )

            else:

                st.warning(
                    "No materials match the current filters. "
                    "Increase the maximum distance or uncertainty, "
                    "or choose another target band gap."
                )

        # ----------------------------------------------------
        # UNCERTAINTY EXPLANATION
        # ----------------------------------------------------

        st.caption(
            "Uncertainty is the standard deviation of Random Forest "
            "tree predictions and should be treated as a model-dispersion "
            "proxy, not a calibrated prediction interval."
        )


