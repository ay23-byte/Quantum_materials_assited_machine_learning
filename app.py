# ============================================================
# DATA LOADING FUNCTIONS
# ============================================================

@st.cache_data
def load_predictions():
    """
    Load predictions generated by the all-material screening script.
    """
    path = RESULTS / "all_material_predictions.csv"

    if not path.exists():
        return pd.DataFrame()

    return pd.read_csv(path)


@st.cache_data
def load_metrics():
    """
    Load final model test metrics.
    """
    path = RESULTS / "final_model_metrics.json"

    if not path.exists():
        return {}

    try:
        return json.loads(path.read_text())
    except Exception:
        return {}


@st.cache_data
def load_group_metrics():
    """
    Load chemical-system GroupKFold validation metrics.
    """
    path = RESULTS / "tuned_groupkfold_summary.json"

    if not path.exists():
        return {}

    try:
        return json.loads(path.read_text())
    except Exception:
        return {}


@st.cache_data
def load_trustworthiness():
    """
    Load trustworthy-ML summary generated by Notebook 06.
    """
    path = RESULTS / "advanced_trustworthiness_summary.json"

    if not path.exists():
        return {}

    try:
        return json.loads(path.read_text())
    except Exception:
        return {}


@st.cache_data
def load_permutation_importance():
    """
    Load permutation feature importance.
    """
    path = RESULTS / "advanced_permutation_importance.csv"

    if not path.exists():
        return pd.DataFrame()

    try:
        return pd.read_csv(path)
    except Exception:
        return pd.DataFrame()


@st.cache_data
def load_shap_importance():
    """
    Load SHAP feature importance.
    """
    path = RESULTS / "shap_feature_importance.csv"

    if not path.exists():
        return pd.DataFrame()

    try:
        return pd.read_csv(path)
    except Exception:
        return pd.DataFrame()


