# ============================================================

with tab7:

    st.subheader("Hypothetical composition discovery")

    st.write(
        "This extension explores composition space beyond the known "
        "JARVIS-DFT materials. It generates charge-balanced binary and "
        "ternary compositions, removes compositions already represented "
        "in JARVIS-DFT, and ranks the remaining candidates using the "
        "existing Random Forest band-gap model."
    )

    st.warning(
        "These are hypothetical composition candidates, not confirmed "
        "new materials. ML prediction alone does not establish crystal "
        "structure, thermodynamic stability, synthesizability, or "
        "experimental novelty. DFT and structural validation are required."
    )

    if hypothetical_candidates.empty:

        st.info(
            "No hypothetical-candidate file is available yet. Run from "
            "the project root: "
            "python src/generate_hypothetical_candidates.py "
            "--target 1.5 --top-k 200"
        )

    else:

        target = st.number_input(
            "Target predicted band gap (eV)",
            min_value=0.0,
            max_value=10.0,
            value=1.5,
            step=0.1,
            key="hypothetical_target",
        )

        max_distance = st.slider(
            "Maximum distance from target (eV)",
            min_value=0.01,
            max_value=2.0,
            value=0.50,
            step=0.01,
            key="hypothetical_distance",
        )

        max_uncertainty = st.slider(
            "Maximum uncertainty proxy (eV)",
            min_value=0.01,
            max_value=3.0,
            value=1.00,
            step=0.01,
            key="hypothetical_uncertainty",
        )

        df = hypothetical_candidates.copy()

        if {
            "predicted_bandgap_eV",
            "uncertainty_proxy_eV",
        }.issubset(df.columns):

            df["distance_from_selected_target_eV"] = (
                df["predicted_bandgap_eV"] - target
            ).abs()

            filtered = df[
                (df["distance_from_selected_target_eV"] <= max_distance)
                & (df["uncertainty_proxy_eV"] <= max_uncertainty)
            ].sort_values(
                [
                    "distance_from_selected_target_eV",
                    "uncertainty_proxy_eV",
                ]
            )

            c1, c2, c3 = st.columns(3)

            c1.metric("Candidate compositions", f"{len(filtered):,}")
            c2.metric(
                "Closest predicted gap",
                (
                    f"{filtered.iloc[0]['predicted_bandgap_eV']:.3f} eV"
                    if not filtered.empty
                    else "N/A"
                ),
            )
            c3.metric(
                "Lowest uncertainty",
                (
                    f"{filtered['uncertainty_proxy_eV'].min():.3f} eV"
                    if not filtered.empty
                    else "N/A"
                ),
            )

            if not filtered.empty:

                st.markdown("### Ranked hypothetical candidates")

                preferred = [
                    "rank",
                    "formula",
                    "predicted_bandgap_eV",
                    "uncertainty_proxy_eV",
                    "distance_from_target_eV",
                    "screening_score",
                    "num_elements",
                    "total_atoms",
                ]

                cols = [c for c in preferred if c in filtered.columns]

                display = filtered[cols].head(100).copy()

                # Avoid Arrow mixed-type serialization in display tables.
                for col in display.columns:
                    if display[col].dtype == "object":
                        display[col] = display[col].astype(str)

                st.dataframe(
                    display,
                    use_container_width=True,
                    hide_index=True,
                )

                st.markdown("### Predicted band gaps")

                chart_df = (
                    filtered[["formula", "predicted_bandgap_eV"]]
                    .head(30)
                    .copy()
                )
                chart_df["formula"] = chart_df["formula"].astype(str)
                chart_df = chart_df.set_index("formula")

                st.bar_chart(
                    chart_df,
                    use_container_width=True,
                )

                st.download_button(
                    "Download hypothetical candidates",
                    data=filtered.to_csv(index=False).encode("utf-8"),
                    file_name="hypothetical_material_candidates.csv",
                    mime="text/csv",
                    use_container_width=True,
                )

            else:

                st.warning(
                    "No hypothetical candidates match the current "
                    "target, distance, and uncertainty filters."
                )

            st.caption(
                "Important limitation: the hypothetical-candidate model "
                "uses composition-derived descriptors. Crystal system and "
                "space group are unknown for generated compositions, so "
                "this is a composition-space prioritization stage rather "
                "than a structure-aware prediction."
            )

        else:

            st.error(
                "The hypothetical-candidate file is missing the expected "
                "prediction columns. Regenerate it with the discovery script."
            )


